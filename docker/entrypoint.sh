#!/bin/sh
set -eu

# CIALLO_UPSTREAM 例：
#   https://your-real-grok2api.example
#   https://host/v1
#   http://host.docker.internal:8000
RAW_UPSTREAM="${CIALLO_UPSTREAM:-}"
RAW_UPSTREAM="$(printf '%s' "$RAW_UPSTREAM" | tr -d '\r' | sed 's/[[:space:]]//g')"

UPSTREAM="$RAW_UPSTREAM"
DISABLED="0"

if [ -z "$UPSTREAM" ]; then
  echo "[ciallo] warn: CIALLO_UPSTREAM 为空 — 前端可启动，但 /v1 代理将返回 503" >&2
  UPSTREAM="https://upstream.invalid"
  DISABLED="1"
fi

# 去掉末尾斜杠
while [ "${UPSTREAM%/}" != "$UPSTREAM" ]; do
  UPSTREAM="${UPSTREAM%/}"
done

# 去掉末尾 /v1（可重复）
case "$UPSTREAM" in
  */v1) UPSTREAM="${UPSTREAM%/v1}" ;;
esac
while [ "${UPSTREAM%/}" != "$UPSTREAM" ]; do
  UPSTREAM="${UPSTREAM%/}"
done

case "$UPSTREAM" in
  https://*|http://*)
    ;;
  *)
    echo "CIALLO_UPSTREAM must start with http:// or https://, got: ${CIALLO_UPSTREAM:-}" >&2
    exit 1
    ;;
esac

# 占位域名：允许容器起来，避免 nginx 启动期 DNS 失败；/v1 返回 503 提示改 .env
case "$UPSTREAM" in
  *your-grok2api.example.com*|*example.com*|*upstream.invalid*)
    echo "[ciallo] warn: CIALLO_UPSTREAM 仍是占位/无效地址: $UPSTREAM" >&2
    echo "[ciallo] warn: 请在 .env 设置真实网关，例如 CIALLO_UPSTREAM=https://grokb.yuzu.gv.uy" >&2
    DISABLED="1"
    ;;
esac

export CIALLO_UPSTREAM_ORIGIN="$UPSTREAM"
export CIALLO_UPSTREAM_DISABLED="$DISABLED"

echo "[ciallo] upstream origin: $CIALLO_UPSTREAM_ORIGIN (disabled=$CIALLO_UPSTREAM_DISABLED)"

# 只替换我们声明的变量，避免误伤 nginx 的 $uri / $request_uri 等
envsubst '${CIALLO_UPSTREAM_ORIGIN} ${CIALLO_UPSTREAM_DISABLED}' \
  < /etc/nginx/nginx.conf.template \
  > /etc/nginx/nginx.conf

# 运行时配置：管理页密码只注入 sha256
ADMIN_PASSWORD="$(printf '%s' "${CIALLO_ADMIN_PASSWORD:-}" | tr -d '\r')"
ADMIN_HASH=""
ADMIN_GATE="false"
if [ -n "$ADMIN_PASSWORD" ]; then
  if command -v sha256sum >/dev/null 2>&1; then
    ADMIN_HASH="$(printf '%s' "$ADMIN_PASSWORD" | sha256sum | awk '{print $1}')"
  elif command -v openssl >/dev/null 2>&1; then
    ADMIN_HASH="$(printf '%s' "$ADMIN_PASSWORD" | openssl dgst -sha256 | awk '{print $NF}')"
  else
    echo "[ciallo] warn: no sha256 tool; admin gate disabled" >&2
    ADMIN_HASH=""
  fi
  if [ -n "$ADMIN_HASH" ]; then
    ADMIN_GATE="true"
    echo "[ciallo] admin gate: enabled (password from env, hash only in runtime-config)"
  fi
else
  echo "[ciallo] admin gate: disabled (CIALLO_ADMIN_PASSWORD empty)"
fi

RUNTIME_JS="/usr/share/nginx/html/runtime-config.js"
cat > "$RUNTIME_JS" <<EOF
/* generated by entrypoint — do not edit */
window.__CIALLO_RUNTIME__ = {
  adminGateEnabled: ${ADMIN_GATE},
  adminPasswordSha256: "${ADMIN_HASH}",
  upstreamConfigured: $([ "$DISABLED" = "1" ] && echo false || echo true)
};
EOF

nginx -t
exec nginx -g 'daemon off;'
