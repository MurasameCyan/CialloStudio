#!/bin/sh
set -eu

# 镜像只托管静态前端；上游 Base URL / API Key 在浏览器管理页配置。
echo "[ciallo] static SPA mode — no CIALLO_UPSTREAM (configure API in Web Admin)"

# nginx 模板无上游变量；直接拷贝即可
if [ -f /etc/nginx/nginx.conf.template ]; then
  cp /etc/nginx/nginx.conf.template /etc/nginx/nginx.conf
fi

# 站长账号：.env 注入用户名 + 密码哈希（不把明文密码写进前端）
# 兼容旧变量 CIALLO_ADMIN_PASSWORD → 站长密码，用户名默认 admin
MASTER_USER="$(printf '%s' "${CIALLO_MASTER_USERNAME:-}" | tr -d '\r' | tr '[:upper:]' '[:lower:]')"
MASTER_PASSWORD="$(printf '%s' "${CIALLO_MASTER_PASSWORD:-${CIALLO_ADMIN_PASSWORD:-}}" | tr -d '\r')"
MASTER_HASH=""

if [ -z "$MASTER_USER" ]; then
  MASTER_USER="admin"
fi

if [ -n "$MASTER_PASSWORD" ]; then
  if command -v sha256sum >/dev/null 2>&1; then
    MASTER_HASH="$(printf '%s' "$MASTER_PASSWORD" | sha256sum | awk '{print $1}')"
  elif command -v openssl >/dev/null 2>&1; then
    MASTER_HASH="$(printf '%s' "$MASTER_PASSWORD" | openssl dgst -sha256 | awk '{print $NF}')"
  else
    echo "[ciallo] warn: no sha256 tool; master password not injected" >&2
    MASTER_HASH=""
  fi
fi

if [ -n "$MASTER_HASH" ]; then
  echo "[ciallo] station master: user=${MASTER_USER} (password from env, hash only in runtime-config)"
else
  echo "[ciallo] station master: not set in env — frontend falls back to mock admin/admin123"
  MASTER_USER=""
  MASTER_HASH=""
fi

# 转义用户名中的引号，避免破坏 JS
MASTER_USER_JS="$(printf '%s' "$MASTER_USER" | sed 's/\\/\\\\/g; s/"/\\"/g')"

# 可选：CF Worker 媒体基址 / 上传 token（非 Telegram Bot Token）
MEDIA_BASE="$(printf '%s' "${CIALLO_MEDIA_BASE:-}" | tr -d '\r')"
MEDIA_UPLOAD_TOKEN="$(printf '%s' "${CIALLO_MEDIA_UPLOAD_TOKEN:-}" | tr -d '\r')"
MEDIA_BASE_JS="$(printf '%s' "$MEDIA_BASE" | sed 's/\\/\\\\/g; s/"/\\"/g')"
MEDIA_TOKEN_JS="$(printf '%s' "$MEDIA_UPLOAD_TOKEN" | sed 's/\\/\\\\/g; s/"/\\"/g')"
if [ -n "$MEDIA_BASE" ]; then
  echo "[ciallo] media worker base: ${MEDIA_BASE}"
fi

RUNTIME_JS="/usr/share/nginx/html/runtime-config.js"
cat > "$RUNTIME_JS" <<EOF
/* generated by entrypoint — do not edit */
window.__CIALLO_RUNTIME__ = {
  masterUsername: "${MASTER_USER_JS}",
  masterPasswordSha256: "${MASTER_HASH}",
  mediaBase: "${MEDIA_BASE_JS}",
  mediaUploadToken: "${MEDIA_TOKEN_JS}"
};
EOF

nginx -t
exec nginx -g 'daemon off;'
